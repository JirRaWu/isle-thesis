/** Built-in Word steps for an issue — works offline without AI. */
export function guideStepsFor(issue: CheckIssue): string[] {
  const base = CATEGORY_STEPS[issue.category] ?? ["对照学院《撰写规范》逐项修改。"];
  if (issue.fixHint) {
    return [...base, `额外提示：${issue.fixHint}`];
  }
  return base;
}
